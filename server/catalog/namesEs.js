/** Translations of a name's ending in brackets ("(Floor 1)", "(Over City)", "(p. 41)"). */
const SUFFIX_ES = [
  [/\(Floor (\d+)\)/, '(Piso $1)'],
  [/\(Over City\/Iron Tangle\)/, '(Ciudad Superior/Maraña de Hierro)'],
  [/\(Over City\)/, '(Ciudad Superior)'],
  [/\(Iron Tangle\)/, '(Maraña de Hierro)'],
  [/\(Bubbles\)/, '(Burbujas)'],
];

/** Spanish name of a book NPC ('' when it has none). */
export function npcNameEs(name) {
  const m = String(name ?? '').match(/^(.*?)\s*(\([^)]*\))?\s*$/);
  const base = (m?.[1] ?? '').trim();
  const es = NPCS_ES[base];
  if (!es) return '';
  let suffix = m?.[2] ?? '';
  for (const [re, rep] of SUFFIX_ES) suffix = suffix.replace(re, rep);
  return suffix ? `${es} ${suffix}` : es;
}
